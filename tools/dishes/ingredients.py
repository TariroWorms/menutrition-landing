def words(key):
    return [w for w in re.split(r'[_\s]+', key.lower()) if w]


def flags(key):
    k = key.lower().strip()
    if k in OVERRIDES:
        f = set(OVERRIDES[k])
    else:
        ws = set(words(k))
        f = set()
        for flag, vocab in WORDS.items():
            for v in vocab:
                if ('_' in v and v in k) or v in ws:
                    f.add(flag)
                    break
    if f & {'pork', 'beef', 'lamb', 'poultry', 'game'}:
        f.add('meat')
        f.discard('unknown_meat')
    if 'unknown_meat' in f:
        f.add('unknown_animal')
    return f
